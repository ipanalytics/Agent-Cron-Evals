"""Load the eval config: which jobs must be alive, and the three global switches.

The config is a plain JSON file so it can be written by hand, generated by a playbook, or
checked into a repository without a schema dependency.
"""

from __future__ import annotations

import json
from pathlib import Path

DEFAULTS: dict = {
    "jobs_file": "~/.hermes/cron/jobs.json",
    "checks": [],
    "delivery": True,
    "streak_limit": 3,
    "self_monitors": [],
    "state_files": [],
    "output": "~/.hermes/data/cron_evals.json",
}


def load(path) -> dict:
    """Read a config file, apply defaults, and refuse the two mistakes that matter."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError("the eval config must be a JSON object")
    config = dict(DEFAULTS)
    config.update(raw)
    if not config.get("checks"):
        raise ValueError("no checks configured: there is nothing to evaluate")
    for item in config["checks"]:
        if not isinstance(item, dict) or not item.get("job"):
            raise ValueError(f"every check needs a job id, got: {item!r}")
    return config


def expand(value: str) -> str:
    """``~`` and environment variables, in one place."""
    import os

    return os.path.expandvars(str(Path(value).expanduser()))
